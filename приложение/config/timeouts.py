"""Таймауты ожидания ответа от ИИ-моделей.

Меняй цифры здесь — применяется при следующем прогоне.
Файл читается один раз при запуске. Перезапуск приложения
не нужен — достаточно нового запуска задачи.

─── ЧТО ЗА ЧТО ОТВЕЧАЕТ ───
"""

# REASONING_START — сколько секунд ждать, пока модель начнёт думать
#   • Модель отвечает слишком поздно → увеличь (до 30)
#   • Модель сразу пишет ответ → уменьши (до 5)
REASONING_START = 15

# REASONING_MIN — минимальный размер «мыслей» (символов)
#   Ниже этого — считаем, что модель ещё не начала думать.
#   • Слишком короткие обрывки — увеличь (до 50)
#   • Ловит мусор вместо мыслей — уменьши (до 5)
REASONING_MIN = 20

# REASONING_STOP — сколько секунд «мыслей» не растут = модель додумала
#   • Модель пишет рывками → увеличь (до 20)
#   • Слишком долго ждём после остановки → уменьши (до 5)
REASONING_STOP = 13

# REASONING_MAX — максимум секунд на «размышления»
#   • Модель долго думает, хочешь обрывать раньше → уменьши (до 60)
#   • Модель не успевает додумать → увеличь (до 300)
REASONING_MAX = 180

# JSON_WAIT — сколько ждать ответа (JSON) после того, как мысли кончились
#   • Ответ приходит медленно → увеличь (до 120)
#   • Ответ должен быть сразу после мыслей → уменьши (до 30)
JSON_WAIT = 60

# FALLBACK — сколько ждать, если модель вообще не думала
#   (сразу пишет ответ, без reasoning)
#   • Долгий ответ без reasoning → увеличь (до 180)
#   • Быстрый ответ → уменьши (до 30)
FALLBACK = 90

# TIMEOUTS — таймауты по попыткам (массив). Каждая попытка = отправка + ожидание.
#   • Если первая попытка часто timeout → увеличь первое число
#   • Если хочешь быстрее сдаваться → уменьши весь массив
#   • Если ждёшь «свет/роутер» → оставь длинный хвост
TIMEOUTS = [60, 90, 180, 600, 1800]

# ─── ПАМЯТКА ───
# Модель долго думает?
#   → REASONING_STOP уменьшить, REASONING_MAX увеличить
#
# Модель не отвечает вообще?
#   → FALLBACK увеличить, TIMEOUTS первое число увеличить
#
# Прогон зависает на 6 минут зря?
#   → TIMEOUTS уменьшить (первые числа)
#
# Прогон не успевает ответить?
#   → TIMEOUTS увеличить (первые числа)
