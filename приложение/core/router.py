"""
Классификация задач для AI Link.

Определяет, что требуется:
  • dialog   — просто ответить (вопрос, объяснение, болтовня)
  • project  — новая задача с файлами (создай, сделай, напиши файл)
  • continue — продолжение работы над проектом
               («продолжим», «теперь код», «проверь», «исправь»)
"""

import re


# === Глаголы для проектных задач (новая задача) ===

PROJECT_VERBS = [
    "создай", "создать", "создайте",
    "сделай", "сделать", "сделайте",
    "напиши файл", "написать файл", "напиши код",
    "добавь", "добавить",
    "измени", "изменить",
    "удали", "удалить",
    "запусти", "запустить",
    "исправь", "исправить",
    "сгенерируй", "сгенерировать",
    "запиши", "записать",
    "перепиши", "переписать",
    "отредактируй",
]


# === Глаголы для диалога (вопрос) ===

DIALOG_VERBS = [
    "расскажи", "объясни", "опиши", "поясни",
    "что такое", "что делает", "что умеет",
    "как работает", "как делается", "как ты",
    "почему", "зачем",
    "чем отличается", "в чём разница",
    "покажи пример", "приведи пример",
    "что ты умеешь", "что ты можешь",
]


# === Регулярки для команд продолжения ===
#
# Ловим «продолжим», «теперь код», «пиши код», «проверь», «исправь».
# Формат: список (regex, что делать). Все проверяются по
# task_lower (регистр не важен).

CONTINUE_PATTERNS = [
    # «продолжим», «продолжай», «продолжаем» — продолжение вообще
    (r"\bпродолж\w*\b", "continue"),
    # «дальше», «давай дальше», «что дальше»
    (r"\b(что\s+)?дальше\b", "continue"),
    # «теперь», «сейчас» + действие
    (r"\b(теперь|сейчас|давай|ну|да)\b.*\b(код|пиш|пис|напиш|созд|сделай|приступ)", "continue"),
    # «пиши код», «пиши-ка код», «пиши теперь», «писать код»
    # Допускаем частицу «-ка», «-же», «-ну» между глаголом и словом.
    (r"\bпиш\w*(?:-\w+)?\s+(код|теперь|дальше|давай)", "continue"),
    # «напишем код», «напишем-ка код», «напишем теперь»
    (r"\bнапиш\w+\s+(код|теперь|дальше)", "continue"),
    # «давай код», «давай писать», «давай-ка код»
    (r"\bдавай\b.*\b(код|пиш|пис|напиш|созд)", "continue"),
    # «приступай», «приступай к коду»
    (r"\bприступ\w*\b", "continue"),
    # «проверь», «проверка», «проверять»
    (r"\bпровер\w*\b", "continue"),
    # «исправь», «починить», «почини»
    (r"\b(исправь|почин\w*)\b", "continue"),
    # «останови», «стоп», «хватит»
    (r"\b(останови|стоп|хватит|прекрати)\b", "continue"),
]


def classify_task(task: str) -> str:
    """Определяет тип задачи.

    Возвращает:
      • "dialog"   — просто ответить (вопрос, объяснение)
      • "project"  — новая задача с файлами
      • "continue" — продолжение работы над проектом
    """
    if not task or not task.strip():
        return "dialog"

    task_lower = task.lower().strip()

    # === 1. Проверяем команды продолжения (высший приоритет) ===
    # Они специфичны и должны ловиться раньше проектных глаголов.
    for pattern, result in CONTINUE_PATTERNS:
        try:
            if re.search(pattern, task_lower):
                return result
        except re.error:
            continue

    # === 2. Проектные глаголы (новая задача) ===
    has_project = any(v in task_lower for v in PROJECT_VERBS)

    # === 3. Диалоговые глаголы ===
    has_dialog = any(v in task_lower for v in DIALOG_VERBS)

    if has_project:
        return "project"
    if has_dialog:
        return "dialog"

    # === 4. Существительные (короткие команды) ===
    project_nouns = ["файл", "скрипт", "программа", "модуль"]
    for n in project_nouns:
        if n in task_lower and len(task_lower.split()) <= 3:
            return "project"

    # === 5. По умолчанию — диалог (безопаснее) ===
    return "dialog"


if __name__ == "__main__":
    # Быстрый тест
    tests = [
        ("привет", "dialog"),
        ("продолжим", "continue"),
        ("теперь пиши код", "continue"),
        ("пиши код", "continue"),
        ("давай код", "continue"),
        ("проверь", "continue"),
        ("исправь ошибки", "continue"),
        ("напишем теперь", "continue"),
        ("создай файл test.py", "project"),
        ("расскажи о Python", "dialog"),
    ]
    for text, expected in tests:
        got = classify_task(text)
        mark = "✓" if got == expected else "✗"
        print(f"  {mark} {text!r:40} → {got} (ждали {expected})")
